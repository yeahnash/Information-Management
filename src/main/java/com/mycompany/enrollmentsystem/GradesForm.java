    public GradesForm() {
        initComponents();
        
        teachID = gradesHelper.getTeacherID();
        gradesHelper.setupGradeComboBoxes(prelimCmbBox, midtermCmbBox, prefiCmbBox, finalCmbBox);
        gradesHelper.showAssign(assignTbl, teachID);

        // Add mouse click listener to assignTbl (Assigned Subjects)
        assignTbl.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                int row = assignTbl.getSelectedRow();
                if (row != -1) {
                    selectedSubjID = assignTbl.getValueAt(row, 0).toString();
                    EnrollmentSystem.globalSubjID = Integer.parseInt(selectedSubjID);
                    gradesHelper.loadEnrolledStudentsAndGrades(gradesTbl, selectedSubjID);
                }
            }
        });

        // Add mouse click listener to gradesTbl (Enrolled Students)
        gradesTbl.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                int row = gradesTbl.getSelectedRow();
                if (row != -1) {
                    studIDTxtField.setText(gradesTbl.getValueAt(row, 0).toString());
                    studNameTxtField.setText(gradesTbl.getValueAt(row, 1).toString());

                    gradesHelper.setComboValue(prelimCmbBox, gradesTbl.getValueAt(row, 2));
                    gradesHelper.setComboValue(midtermCmbBox, gradesTbl.getValueAt(row, 3));
                    gradesHelper.setComboValue(prefiCmbBox, gradesTbl.getValueAt(row, 4));
                    gradesHelper.setComboValue(finalCmbBox, gradesTbl.getValueAt(row, 5));
                }
            }
        });

        // Add action listener to submitBtn
        submitBtn.addActionListener(e -> {
            gradesHelper.saveGrades(
                this, 
                studIDTxtField.getText().trim(), 
                selectedSubjID, 
                String.valueOf(prelimCmbBox.getSelectedItem()), 
                String.valueOf(midtermCmbBox.getSelectedItem()), 
                String.valueOf(prefiCmbBox.getSelectedItem()), 
                String.valueOf(finalCmbBox.getSelectedItem()), 
                gradesTbl
            );
        });
    }

